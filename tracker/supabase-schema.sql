-- UangKu — Supabase (Postgres) schema
-- Source of truth pindah dari sqlite VPS (~/workspace/uang-tracker/data.db).
-- Data saat migrasi: 8 accounts, 42 transactions, 3 investments, 4 prices (10 Nov 2026).
-- Jalankan di Supabase SQL Editor, lalu migrasi data dari sqlite (uang_supabase_migrate.py).
-- RLS: sengaja belum diaktifkan — akses server-side pakai service_role key dari CLI.
-- Kalau nanti PWA baca langsung dari Supabase (anon key), aktifkan RLS + policy SELECT
-- untuk anon di keempat tabel ini.

CREATE TABLE IF NOT EXISTS accounts (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'bank',
    balance NUMERIC NOT NULL DEFAULT 0,
    note TEXT DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    account_no TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS transactions (
    id INTEGER PRIMARY KEY,
    date DATE NOT NULL,
    amount INTEGER NOT NULL,
    direction TEXT NOT NULL CHECK (direction IN ('in', 'out')),
    category TEXT DEFAULT 'lain-lain',
    account_id INTEGER REFERENCES accounts(id),
    note TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS investments (
    id INTEGER PRIMARY KEY,
    kind TEXT NOT NULL,
    symbol TEXT NOT NULL,
    qty NUMERIC NOT NULL,
    avg_price NUMERIC NOT NULL,
    date DATE NOT NULL,
    note TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS prices (
    symbol TEXT PRIMARY KEY,
    price NUMERIC NOT NULL,
    source TEXT DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Urutan insert saat migrasi: accounts -> transactions -> investments -> prices.
-- Setelah insert, reset sequence id (kalau pakai GENERATED BY DEFAULT AS IDENTITY,
-- lewati langkah ini; skema ini memakai id eksplisit dari sqlite agar id tx tetap sama).
