-- - Data lama menjadi milik owner_id = 'ade'.
-- - Akun awal owner_id = 'pacar' dibuat: id 16, nama "Utama", saldo 0.
-- - Tabel api_keys menyimpan hash API key per owner (plaintext tidak disimpan).
-- - RLS dinyalakan tanpa policy anon: anon tidak bisa baca/tulis.
--   Service role (CLI + Vercel API) tetap bypass RLS.

ALTER TABLE accounts
  ADD COLUMN IF NOT EXISTS owner_id TEXT NOT NULL DEFAULT 'ade';
ALTER TABLE transactions
  ADD COLUMN IF NOT EXISTS owner_id TEXT NOT NULL DEFAULT 'ade';
ALTER TABLE investments
  ADD COLUMN IF NOT EXISTS owner_id TEXT NOT NULL DEFAULT 'ade';

CREATE TABLE IF NOT EXISTS api_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id TEXT NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    label TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_accounts_owner ON accounts(owner_id);
CREATE INDEX IF NOT EXISTS idx_transactions_owner_date ON transactions(owner_id, date DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_investments_owner ON investments(owner_id);
CREATE INDEX IF NOT EXISTS idx_api_keys_owner ON api_keys(owner_id);

